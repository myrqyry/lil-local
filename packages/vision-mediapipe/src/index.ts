type MinimalLandmark = { x: number; y: number; z?: number }
type MinimalCategory = { categoryName: string; score: number; index?: number; displayName?: string }
const convertLandmarks = (points: readonly MinimalLandmark[] = []): VisionLandmark[] =>
  points.map(({ x, y, z }) => ({ x, y, z: z ?? 0 }))
const convertCategories = (categories: readonly MinimalCategory[] = []): VisionScore[] =>
  categories.filter(x => Number.isFinite(x.score)).map(({ categoryName, score }) => ({ categoryName, score }))

/** Preserve per-face alignment. Never use first face's blendshapes for every face. */
export function mapFaceLandmarkerResult(
  result: { faceLandmarks: readonly (readonly MinimalLandmark[])[]; faceBlendshapes: readonly { categories: readonly MinimalCategory[] }[] },
): FaceVisionResult {
  return {
    kind: 'face-landmarks',
    faces: result.faceLandmarks.map((landmarks, i) => ({
      landmarks: convertLandmarks(landmarks),
      blendshapes: convertCategories(result.faceBlendshapes[i]?.categories),
    })),
  }
}

/** Keep all real scores; downstream apps decide gesture actions and safety gating. */
export function mapGestureRecognizerResult(
  result: { gestures: readonly (readonly MinimalCategory[])[]; handedness: readonly (readonly MinimalCategory[])[]; landmarks: readonly (readonly MinimalLandmark[])[]; worldLandmarks: readonly (readonly MinimalLandmark[])[] },
): GestureVisionResult {
  return {
    kind: 'gestures',
    hands: result.gestures.map((classifications, i) => {
      const gestures = convertCategories(classifications)
      const label = result.handedness[i]?.[0]?.categoryName
      return {
        landmarks: convertLandmarks(result.landmarks[i]),
        worldLandmarks: convertLandmarks(result.worldLandmarks[i]),
        gestures,
        topGesture: gestures[0] ?? null,
        handedness: label === 'Left' || label === 'Right' ? label : 'Unknown',
      }
    }),
  }
}

type MinimalPoseLandmark = { x: number; y: number; z: number; visibility?: number; presence?: number }

/** Preserve per-person alignment and native visibility/presence scores. */
export function mapPoseLandmarkerResult(
  result: {
    landmarks: readonly (readonly MinimalPoseLandmark[])[]
    worldLandmarks: readonly (readonly MinimalPoseLandmark[])[]
  },
): PoseVisionResult {
  if (result.landmarks.length !== result.worldLandmarks.length)
    throw new Error('Pose count mismatch between image and world landmarks')
  const copy = (points: readonly MinimalPoseLandmark[]): PoseVisionLandmark[] =>
    points.map(point => ({
      x: point.x, y: point.y, z: point.z,
      ...(point.visibility === undefined ? {} : { visibility: point.visibility }),
      ...(point.presence === undefined ? {} : { presence: point.presence }),
    }))
  return {
    kind: 'pose-landmarks',
    poses: result.landmarks.map((landmarks, i) => ({
      landmarks: copy(landmarks),
      worldLandmarks: copy(result.worldLandmarks[i]),
    })),
  }
}

type MinimalObjectCategory = {index: number; categoryName: string; displayName: string; score: number}
type MinimalObjectBox = ObjectVisionBoundingBox
type MinimalObjectKeypoint = ObjectVisionKeypoint

/** Native categories remain per-object and native boxes remain pixel-space. */
export function mapObjectDetectorResult(
  result: {
    detections: readonly {
      categories: readonly MinimalObjectCategory[]
      boundingBox?: MinimalObjectBox
      keypoints: readonly MinimalObjectKeypoint[]
    }[]
  },
): ObjectVisionResult {
  return {
    kind: 'object-detections',
    detections: result.detections.map((detection) => {
      const box = detection.boundingBox
      if (box && (![
        box.originX, box.originY, box.width, box.height, box.angle,
      ].every(Number.isFinite) || box.width < 0 || box.height < 0))
        throw new Error('MediaPipe object bounding box must have finite, nonnegative pixel dimensions')
      const categories = detection.categories.map((category) => {
        if (!Number.isFinite(category.score) || category.score < 0 || category.score > 1)
          throw new Error('MediaPipe object category score must be a finite probability')
        return {
          index: category.index,
          categoryName: category.categoryName,
          displayName: category.displayName,
          score: category.score,
        }
      })
      const keypoints = detection.keypoints.map((point) => {
        if (![point.x, point.y].every(Number.isFinite) ||
            (point.score !== undefined && !Number.isFinite(point.score)))
          throw new Error('MediaPipe object keypoint coordinates and score must be finite')
        return {
          x: point.x, y: point.y,
          ...(point.label === undefined ? {} : {label: point.label}),
          ...(point.score === undefined ? {} : {score: point.score}),
        }
      })
      return {
        categories,
        keypoints,
        ...(box === undefined ? {} : {boundingBox: {...box}}),
      }
    }),
  }
}

/**
 * Preserve all classifier heads and classes instead of flattening the first
 * head into a guessed single-label result.
 */
export function mapImageClassifierResult(
  result: {
    timestampMs?: number
    classifications: readonly {
      headIndex: number
      headName: string
      categories: readonly {index:number;categoryName:string;displayName:string;score:number}[]
    }[]
  },
): ImageClassifierVisionResult {
  if (result.timestampMs !== undefined &&
      (!Number.isFinite(result.timestampMs) || result.timestampMs < 0))
    throw new Error('Image classification timestamp must be finite and nonnegative')
  return {
    kind: 'image-classifications',
    ...(result.timestampMs === undefined ? {} : {timestampMs: result.timestampMs}),
    heads: result.classifications.map(head => ({
      headIndex: head.headIndex,
      headName: head.headName,
      categories: head.categories.map(category => {
        if (!Number.isFinite(category.score) || category.score < 0 || category.score > 1)
          throw new Error('Image classifier score must be a finite probability')
        return {
          index: category.index,
          categoryName: category.categoryName,
          displayName: category.displayName,
          score: category.score,
        }
      }),
    })),
  }
}

type HolisticLandmark = {x:number;y:number;z:number;visibility?:number;presence?:number}
type HolisticCategories = {categories:readonly MinimalCategory[]}

/** One model's complete result, with no synthetic gesture labels or swapped hands. */
export function mapHolisticLandmarkerResult(result:{
  faceLandmarks:readonly (readonly HolisticLandmark[])[]
  faceBlendshapes:readonly HolisticCategories[]
  poseLandmarks:readonly (readonly HolisticLandmark[])[]
  poseWorldLandmarks:readonly (readonly HolisticLandmark[])[]
  leftHandLandmarks:readonly (readonly HolisticLandmark[])[]
  leftHandWorldLandmarks:readonly (readonly HolisticLandmark[])[]
  rightHandLandmarks:readonly (readonly HolisticLandmark[])[]
  rightHandWorldLandmarks:readonly (readonly HolisticLandmark[])[]
}):HolisticVisionResult {
  if(result.poseLandmarks.length!==result.poseWorldLandmarks.length)
    throw new Error('Holistic pose count mismatch between normalized and world landmarks')
  if(result.leftHandLandmarks.length!==result.leftHandWorldLandmarks.length)
    throw new Error('Holistic left hand count mismatch')
  if(result.rightHandLandmarks.length!==result.rightHandWorldLandmarks.length)
    throw new Error('Holistic right hand count mismatch')
  if(result.faceBlendshapes.length &&
      result.faceLandmarks.length!==result.faceBlendshapes.length)
    throw new Error('Holistic face count mismatch between landmarks and blendshapes')
  const copy=(points:readonly HolisticLandmark[]):PoseVisionLandmark[]=>
    points.map(point=>{
      if(![point.x,point.y,point.z].every(Number.isFinite))
        throw new Error('Holistic landmark coordinates must be finite')
      for(const key of ['visibility','presence'] as const) {
        const val=point[key]
        if(val!==undefined && (!Number.isFinite(val)||val<0||val>1))
          throw new Error('Holistic landmark '+key+' must be a finite probability')
      }
      return {
        x:point.x,y:point.y,z:point.z,
        ...(point.visibility===undefined?{}:{visibility:point.visibility}),
        ...(point.presence===undefined?{}:{presence:point.presence}),
      }
    })
  const categories=(source:readonly MinimalCategory[]):VisionScore[]=>source.map(item=>{
    if(!item.categoryName || !Number.isFinite(item.score)||item.score<0||item.score>1)
      throw new Error('Holistic blendshape score must be finite in [0,1]')
    return {categoryName:item.categoryName,score:item.score}
  })
  const hands:HolisticVisionResult['hands']=[]
  for(const [side,normalized,world] of [
    ['left',result.leftHandLandmarks,result.leftHandWorldLandmarks],
    ['right',result.rightHandLandmarks,result.rightHandWorldLandmarks],
  ] as const) {
    normalized.forEach((landmarks,index)=>hands.push({
      side,landmarks:copy(landmarks),worldLandmarks:copy(world[index]),
    }))
  }
  return {
    kind:'holistic-landmarks',
    faces:result.faceLandmarks.map((landmarks,i)=>({
      landmarks:copy(landmarks),
      blendshapes:categories(result.faceBlendshapes[i]?.categories??[]),
    })),
    poses:result.poseLandmarks.map((landmarks,i)=>({
      landmarks:copy(landmarks),worldLandmarks:copy(result.poseWorldLandmarks[i]),
    })),
    hands,
  }
}

/**
 * Copy the native borrowed MediaPipe mask before its callback releases it.
 * Do not flatten pixel-category IDs to a single mask or assume 0 is 'dog'.
 */
export function copySemanticCategoryMask(input: {
  width:number;height:number;values:Uint8Array;
  labels:readonly string[];qualityScores?:readonly number[]
}):SemanticVisionResult {
  const {width,height,values,labels,qualityScores}=input
  if(!Number.isSafeInteger(width)||!Number.isSafeInteger(height)||
     width<1||height<1||width*height>4_194_304)
    throw new Error('Semantic mask dimensions must be positive and within 4M pixels')
  if(!(values instanceof Uint8Array)||values.length!==width*height)
    throw new Error('Semantic mask length must equal its pixel dimensions')
  if(!Array.isArray(labels)||labels.some(x=>typeof x!=='string'))
    throw new Error('Semantic mask labels must be strings')
  if(qualityScores!==undefined && (!Array.isArray(qualityScores)||
      qualityScores.some(x=>!Number.isFinite(x)||x<0||x>1)))
    throw new Error('Semantic mask quality scores must be finite probabilities')
  return {
    kind:'semantic-segmentation',width,height,
    categoryIds:Uint8Array.from(values),
    labels:[...labels],
    ...(qualityScores===undefined?{}:{qualityScores:[...qualityScores]}),
  }
}

/**
 * Keep normalized strokes and polarity intact. A single tap isn't a stroke;
 * the SDK requires a completed line of meaningful length.
 */
export function validateInteractiveStrokes(
  strokes:readonly InteractiveSelectionStroke[],
):Stroke[]{
  if(!Array.isArray(strokes)||!strokes.length)
    throw new Error('Provide at least one completed stroke')
  if(strokes.length>32)throw new Error('Too many interactive strokes (max 32)')
  const modeToNumber={positive:1,negative:2,lasso:3} as const
  if(strokes.some(stroke=>!stroke || !Object.prototype.hasOwnProperty.call(modeToNumber,stroke.mode)))
    throw new Error('Invalid interactive stroke mode')
  if(!strokes.some(stroke=>stroke.mode==='positive'||stroke.mode==='lasso'))
    throw new Error('At least one positive or lasso stroke is required')
  return strokes.map((stroke:InteractiveSelectionStroke,index:number)=>{
    if(!stroke || !Object.prototype.hasOwnProperty.call(modeToNumber,stroke.mode))
      throw new Error('Invalid interactive stroke mode at index '+index)
    if(!Array.isArray(stroke.points)||stroke.points.length<2||stroke.points.length>256)
      throw new Error('Interactive stroke requires 2 to 256 points')
    let length=0
    const points=stroke.points.map((point:{x:number;y:number},i:number)=>{
      if(!point || !Number.isFinite(point.x)||!Number.isFinite(point.y)||
         point.x<0||point.y<0||point.x>1||point.y>1)
        throw new Error('Interactive stroke points must use normalized [0,1] coordinates')
      if(i>0)length+=Math.hypot(point.x-stroke.points[i-1].x,point.y-stroke.points[i-1].y)
      return {x:point.x,y:point.y}
    })
    if(length<.05)throw new Error('Interactive stroke length must be at least 0.05 normalized units')
    return {
      brushMode:modeToNumber[stroke.mode],
      point:points,
      isCompleted:true,
    }
  })
}

/** A fresh copy; nothing references the native mask once its owner closes. */
export function copyInteractiveMask(input:{
  width:number;height:number;values:Float32Array,
}):Extract<InteractiveSelectionResult,{kind:'interactive-segmentation'}>{
  const {width,height,values}=input
  if(!Number.isSafeInteger(width)||!Number.isSafeInteger(height)||width<1||height<1||
     width*height>4_194_304)
    throw new Error('Interactive mask dimensions must be positive and under 4M pixels')
  if(!(values instanceof Float32Array)||values.length!==width*height)
    throw new Error('Interactive mask length must equal its width × height')
  if(values.some(value=>!Number.isFinite(value)||value<0||value>1))
    throw new Error('Interactive mask confidence must be finite in [0,1]')
  return {kind:'interactive-segmentation',width,height,confidence:Float32Array.from(values)}
}

